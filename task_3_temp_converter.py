# ============= ЗАДАЧА 3: Конвертер температур =============

# Исходные данные
celsius = 25.0  # температура в градусах Цельсия

# ============= Перевод в Фаренгейты
# Формула: F = C × 9/5 + 32
fahrenheit = celsius * 9/5 + 32

# ============= Определение состояния воды
if celsius <= 0:
    state = "Лёд"
elif 1 <= celsius <= 99:
    state = "Жидкость"
else:
    state = "Пар"

# ============= Округление
fahrenheit = round(fahrenheit, 2)

# ============= Вывод результатов

print("ЗАДАЧА 3: Конвертер температур")
print("=" * 40)
print(f"Температура в °C:  {celsius}")
print(f"Температура в °F:  {fahrenheit}")
print(f"Состояние воды:    {state}")
print("")